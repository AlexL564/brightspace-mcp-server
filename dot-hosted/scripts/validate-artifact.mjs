import { readFile } from 'node:fs/promises';
import assert from 'node:assert/strict';
const manifest=JSON.parse(await readFile('dist/.openai/hosting.json','utf8'));
assert.ok(manifest.project_id);
assert.ok(manifest.capabilities.includes('mcp'));
assert.equal(manifest.r2,'CONNECTIONS');
const source=await readFile('dist/server/index.js','utf8');
const worker=await import('data:text/javascript;base64,'+Buffer.from(source).toString('base64'));
assert.equal(typeof worker.default.fetch,'function');
const response=await worker.default.fetch(new Request('https://example.test/mcp',{method:'POST',body:JSON.stringify({jsonrpc:'2.0',id:1,method:'tools/list'})}),{});
assert.equal(response.status,200);
assert.equal((await response.json()).result.tools.length,6);
console.log('Worker artifact valid: six read-only tools, encrypted storage binding.');
